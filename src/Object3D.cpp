#include "Object3D.h"
#include <glm/gtc/matrix_transform.hpp>

Object3D::Object3D(glm::vec3 pos, glm::vec3 sc, glm::vec3 rot, glm::vec3 alb, float met, float rough, GLuint texID)
    : position(pos), scale(sc), rotation(rot) {
    material.albedo = alb;
    material.metallic = met;
    material.roughness = rough;
    material.textureID = texID;
    material.hasTexture = (texID != 0);
    SetupMesh();
}

Object3D::~Object3D() {
    glDeleteVertexArrays(1, &VAO);
    glDeleteBuffers(1, &VBO);
}

